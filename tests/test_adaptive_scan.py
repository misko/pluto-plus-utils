from __future__ import annotations

import dataclasses
import hashlib

import pytest

from pluto_plus.adaptive_scan import (
    ACK_BYTES,
    CAPS_BYTES,
    FEEDBACK_BYTES,
    SETUP_BYTES,
    TERMINAL_BYTES,
    VISIT_BYTES,
    VISIT_DEADLINE_FORCED,
    AdaptiveScanProtocolError,
    FeedbackResult,
    ScanAck,
    ScanCapabilities,
    ScanFeedback,
    ScanOutcome,
    ScanSetup,
    ScanTarget,
    ScanTerminal,
    ScanVisit,
    TerminalState,
    VisitResult,
    corruptions,
)


def setup() -> ScanSetup:
    return ScanSetup(
        session=0x1122334455667788,
        generation=9,
        seed=10,
        source_rate_hz=15_000_000,
        analog_bandwidth_hz=12_000_000,
        duration_ms=300_000,
        dwell_ms=240,
        transition_budget_ms=10,
        maximum_revisit_ms=3_000,
        feedback_age_ms=1_000,
        application_delay_ms=1_000,
        decay_ms=5_000,
        maximum_boost=3,
        maximum_queue_bytes=200_000_000,
        maximum_queue_age_ms=5_000,
        maximum_queue_visits=50,
        analysis_digest=bytes(range(1, 33)),
        targets=tuple(
            ScanTarget(
                channel=100 + index,
                profile=index * 2,
                frequency_hz=2_400_000_000 + 25_000_000 * index,
                baseline_weight=index + 1,
                profile_crc32=0x10203040 + index,
            )
            for index in range(3)
        ),
    )


def test_setup_matches_c_golden_and_rejects_every_corruption() -> None:
    request = setup()
    packed = request.pack()
    assert len(packed) == SETUP_BYTES
    # Generated by test_spf_scan_protocol from the independently implemented C codec.
    assert hashlib.sha256(packed).hexdigest() == (
        "b48e7c2d4947f134b4d9bf2840a46a58fb26da4cc4b7cf03ef7165c7e3ad0dda"
    )
    assert ScanSetup.unpack(packed) == request
    for changed in corruptions(packed):
        with pytest.raises(AdaptiveScanProtocolError):
            ScanSetup.unpack(changed)


